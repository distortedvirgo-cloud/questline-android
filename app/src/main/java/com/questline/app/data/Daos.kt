@Dao
interface TxnDao {
    @Insert
    suspend fun insert(txn: Txn): Long

    @Query("DELETE FROM transactions WHERE id = :id")
    suspend fun delete(id: Long)

    @Query("SELECT * FROM transactions WHERE epochDay BETWEEN :fromDay AND :toDay ORDER BY epochDay DESC, id DESC")
    fun observeRange(fromDay: Long, toDay: Long): Flow<List<Txn>>

    @Query("SELECT SUM(CASE WHEN type='EXPENSE' THEN amountMinor ELSE -amountMinor END) FROM transactions WHERE epochDay BETWEEN :fromDay AND :toDay")
    suspend fun netSpent(fromDay: Long, toDay: Long): Long?

    @Query("SELECT COALESCE(SUM(amountMinor),0) FROM transactions WHERE type='EXPENSE' AND categoryId=:categoryId AND epochDay BETWEEN :fromDay AND :toDay")
    suspend fun spentInCategory(categoryId: Long, fromDay: Long, toDay: Long): Long

    @Query("SELECT COALESCE(SUM(amountMinor),0) FROM transactions WHERE type='EXPENSE' AND categoryId=:categoryId AND epochDay BETWEEN :fromDay AND :toDay")
    fun observeSpentInCategory(categoryId: Long, fromDay: Long, toDay: Long): Flow<Long>

    // --- T-15: бэкап ---
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(txns: List<Txn>)

    @Query("SELECT * FROM transactions")
    suspend fun all(): List<Txn>

    @Query("DELETE FROM transactions")
    suspend fun clearAll()

    /** Чистое движение (доходы − расходы) по времени создания — для карты текущего баланса */
    @Query("SELECT COALESCE(SUM(CASE WHEN type='INCOME' THEN amountMinor ELSE -amountMinor END),0) FROM transactions WHERE createdAtMillis >= :sinceMillis")
    fun observeNetSince(sinceMillis: Long): kotlinx.coroutines.flow.Flow<Long>
}

@Dao
interface PendingTxnDao {
    @Insert(onConflict = OnConflictStrategy.IGNORE)
    suspend fun insert(pending: PendingTxn): Long

    @Query("SELECT * FROM pending_txn WHERE status = 'PENDING' ORDER BY receivedMillis DESC")
    fun observePending(): Flow<List<PendingTxn>>

    @Query("UPDATE pending_txn SET status = :status WHERE id = :id")
    suspend fun setStatus(id: Long, status: String)

    /** Дедупликация: тот же текст в пределах ±5 минут уже есть? */
    @Query("SELECT COUNT(*) FROM pending_txn WHERE text = :text AND ABS(receivedMillis - :receivedMillis) < 300000")
    suspend fun isDuplicate(text: String, receivedMillis: Long): Int

    @Query("DELETE FROM pending_txn WHERE status != 'PENDING' AND receivedMillis < :cutoffMillis")
    suspend fun cleanupOld(cutoffMillis: Long)

    // --- T-15: бэкап ---
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(pending: List<PendingTxn>)

    @Query("SELECT * FROM pending_txn")
    suspend fun all(): List<PendingTxn>

    @Query("DELETE FROM pending_txn")
    suspend fun clearAll()
}

